import React, { useEffect, useRef, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { UnifiedChatPanel, listStoredConversations, type DockAction, type StoredConversationMeta } from '../../components/chat/UnifiedChatPanel';
import { Bot, Code, Globe, MessageSquarePlus, Smartphone } from 'lucide-react';
import { MobilePreviewPanel } from '../../components/customer/MobilePreviewPanel';
import { MobileSimulator } from '../../components/customer/MobileSimulator';
import { BrowserPreview as LiveBrowserPreview } from '../../components/customer/BrowserPreview';

// Honest preview contract: the preview tabs only make sense AFTER the AI has
// generated real HTML and the user pressed Preview on a code block. Before that
// they used to show a blank white iframe behind a fake "Live Preview" URL —
// owner-reported white screens. hasPreview guards the iframe render.
const CODE_PLACEHOLDER = '<!-- Code generated by SupremeAI will appear here -->';

// OWNER DECISION (2026-10-25, Banglish request — reaffirmed after peer #1190
// merge): Manual-work UI (Auto/Manual toggle + HTML workbench) দুই প্রিভিউ
// ট্যাব থেকেই বাদ। Browser ট্যাব = agent-only; Mobile ট্যাব = dual-path
// (agent build + সরাসরি URL খোলা) — self-serve manual editor নেই। Peer
// #1190-এর mirror + surface-memory ফিচার অক্ষত রাখা হয়েছে।
// MOBILE DUAL-PATH (owner request 2026-10-25): which preview surface (Browser
// or Mobile) the user last chose — chat-এ Preview চাপলে agent-built কাজ এই
// সারফেসেই খোলে, সবসময় Browser ট্যাবে force-jump করে না।
const PREVIEW_SURFACE_STORE = 'supremeai_preview_surface_v1';

// MOBILE DUAL-PATH (owner request 2026-10-25, Banglish): mobile simulator আর
// "back to conversation"-এ force করবে না। এখন ২ ভাবে চলে — (১) USER PATH:
// ইউজার নিজে এই স্ক্রিনে manual HTML লিখতে পারে বা সরাসরি URL খুলতে পারে,
// conversation-এ ফেরা ঐচ্ছিক; (২) AGENT PATH: chat-এ Preview চাপলে agent-built
// অ্যাপ ইউজারের শেষ পছন্দের সারফেসে (browser বা mobile) খোলে, আর Browser
// Preview-তে agent/ইউজার যে পেজে যায় তা render-ticket proxy দিয়ে এই ফোনে
// mirror হয়।
interface MobileAutoPanelProps {
  hasPreview: boolean;
  code: string;
  mirrorUrl: string;
  source: 'agent' | 'mirror';
  onSourceChange: (s: 'agent' | 'mirror') => void;
  onBack: () => void;
  onOpenUrl: (url: string) => void;
  urlDraft: string;
  onUrlDraftChange: (v: string) => void;
}

const MobileAutoPanel: React.FC<MobileAutoPanelProps> = ({
  hasPreview, code, mirrorUrl, source, onSourceChange, onBack, onOpenUrl, urlDraft, onUrlDraftChange,
}) => {
  const showAgent = hasPreview && (source === 'agent' || !mirrorUrl);
  const showMirror = Boolean(mirrorUrl) && (source === 'mirror' || !hasPreview);
  const showChips = hasPreview && Boolean(mirrorUrl);
  return (
    <div className="flex h-full min-h-0 w-full flex-col gap-3">
      {showChips && (
        <div className="flex w-fit shrink-0 items-center gap-1 rounded-full border border-[var(--sa-border)] bg-[var(--sa-surface)]/80 p-1" data-testid="mobile-source-toggle">
          <button
            type="button"
            onClick={() => onSourceChange('agent')}
            aria-pressed={source === 'agent'}
            title="What the SupremeAI agent built from the conversation"
            className={`rounded-full px-3 py-1.5 text-[11px] font-medium transition-colors ${source === 'agent' ? 'bg-[var(--sa-primary)] text-white' : 'text-[var(--sa-ink-muted)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            🤖 Agent build
          </button>
          <button
            type="button"
            onClick={() => onSourceChange('mirror')}
            aria-pressed={source === 'mirror'}
            title="Live mirror of the page open in Browser Preview"
            className={`rounded-full px-3 py-1.5 text-[11px] font-medium transition-colors ${source === 'mirror' ? 'bg-[var(--sa-primary)] text-white' : 'text-[var(--sa-ink-muted)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            🌐 Browser mirror
          </button>
        </div>
      )}
      {showAgent ? (
        <div className="min-h-0 flex-1">
          <MobilePreviewPanel html={code} title="SupremeAI agent build — mobile" />
        </div>
      ) : showMirror ? (
        <div className="min-h-0 flex-1">
          <MobileSimulator url={mirrorUrl} />
        </div>
      ) : (
        <MobileEmptyState onBack={onBack} onOpenUrl={onOpenUrl} urlDraft={urlDraft} onUrlDraftChange={onUrlDraftChange} />
      )}
    </div>
  );
};

const MobileEmptyState: React.FC<{
  onBack: () => void;
  onOpenUrl: (url: string) => void;
  urlDraft: string;
  onUrlDraftChange: (v: string) => void;
}> = ({ onBack, onOpenUrl, urlDraft, onUrlDraftChange }) => (
  <div className="flex h-full w-full items-center justify-center rounded-2xl border border-dashed border-white/10 bg-slate-900/40 p-6">
    <div className="flex max-w-md flex-col items-center gap-3 text-center">
      <span className="flex size-12 items-center justify-center rounded-xl border border-white/10 bg-slate-900 text-slate-400">
        <Smartphone size={20} />
      </span>
      <h3 className="text-base font-semibold text-slate-200">Your mobile simulator — drive it yourself</h3>
      <p className="text-sm leading-6 text-slate-500">
        Ask SupremeAI to build something in the conversation, press{' '}
        <span className="font-medium text-slate-300">Preview</span>, and it opens right here on this
        phone frame when Mobile is your chosen surface. No conversation needed either — start below.
      </p>
      <div className="flex flex-wrap items-center justify-center gap-2">
        <button
          type="button"
          onClick={onBack}
          className="rounded-lg border border-white/10 bg-slate-900/80 px-4 py-2 text-xs font-medium text-slate-300 transition hover:border-purple-400/40 hover:text-white"
        >
          ← Back to conversation
        </button>
      </div>
      <form
        onSubmit={(e) => {
          e.preventDefault();
          const v = urlDraft.trim();
          if (/^https?:\/\//i.test(v)) onOpenUrl(v);
        }}
        className="mt-1 flex w-full items-center gap-2"
        data-testid="mobile-url-form"
      >
        <div className="flex flex-1 items-center gap-2 rounded-lg border border-white/10 bg-slate-900/80 px-3 py-2">
          <Globe size={13} className="shrink-0 text-slate-500" />
          <input
            type="text"
            value={urlDraft}
            onChange={(e) => onUrlDraftChange(e.target.value)}
            placeholder="https://any-site.com — open it on the phone"
            data-testid="mobile-url-input"
            aria-label="URL to preview on the mobile simulator"
            className="w-full bg-transparent font-mono text-[11px] text-slate-200 outline-none placeholder:text-slate-600"
          />
        </div>
        <button
          type="submit"
          disabled={!/^https?:\/\//i.test(urlDraft.trim())}
          className="shrink-0 rounded-lg border border-cyan-400/40 bg-cyan-500/10 px-3 py-2 text-xs font-medium text-cyan-200 transition hover:bg-cyan-500/20 disabled:cursor-not-allowed disabled:opacity-40"
        >
          Open
        </button>
      </form>
    </div>
  </div>
);

export const AIStudio: React.FC = () => {
  const [input, setInput] = useState('');
  const [resumeConvId, setResumeConvId] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState<'chat' | 'preview' | 'mobile'>('chat');
  // CHAT LANDING (owner decision 2026-10-24): Chat is the landing tab with a
  // local history sidebar (mainstream-AI pattern). Home and Prompt Library
  // left the rail; users enable features from Settings/Profile.
  const [history, setHistory] = useState<StoredConversationMeta[]>([]);
  useEffect(() => {
    setHistory(listStoredConversations());
  }, [activeTab, resumeConvId]);
  const startNewChat = () => {
    const freshId = `conv-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    setResumeConvId(freshId);
  };
  const [code, setCode] = useState(CODE_PLACEHOLDER);
  const hasPreview = code.trim() !== '' && code !== CODE_PLACEHOLDER;
  // MOBILE DUAL-PATH state (owner request 2026-10-25): mirrorUrl = Browser
  // Preview-তে agent/ইউজার সর্বশেষ যে পেজে navigate করেছে (সেটাই মোবাইলে
  // mirror হয়); lastSurface = ইউজারের শেষ পছন্দের preview সারফেস (chat-এর
  // Preview action এখানেই খোলে); mobileSource = agent-build নাকি browser-mirror।
  const [mirrorUrl, setMirrorUrl] = useState('');
  const [mobileSource, setMobileSource] = useState<'agent' | 'mirror'>('agent');
  const [mobileUrlDraft, setMobileUrlDraft] = useState('');
  const [lastSurface, setLastSurface] = useState<'preview' | 'mobile'>(() =>
    localStorage.getItem(PREVIEW_SURFACE_STORE) === 'mobile' ? 'mobile' : 'preview');
  useEffect(() => { localStorage.setItem(PREVIEW_SURFACE_STORE, lastSurface); }, [lastSurface]);
  const gotoSurface = (tab: 'preview' | 'mobile') => {
    setLastSurface(tab);
    setActiveTab(tab);
  };
  const [searchParams, setSearchParams] = useSearchParams();
  const intentConsumedRef = useRef(false);

  // বাংলা মন্তব্য (FIX intent-carryover #2519): ?intent= প্যারামিটার আর auto-send হয় না —
  // আগে `void handleSend(intent)` সরাসরি AI-তে পাঠাত, ফলে attacker-চিহ্নিত URL দিয়ে
  // prompt-injection করা যেত (ব্যবহারকারী কিছু দেখার আগেই প্রম্পট execute)। Root-cause
  // fix: প্যারামটি consume করে composer input-এ prefill + focus করা হয়, যাতে ব্যবহারকারী
  // টেক্সট নিজের চোখে দেখে স্পষ্টভাবে Send চাপে। ref guard StrictMode-এর double
  // effect-invoke-এ দ্বিগুণ prefill আটকায়; param strip (replace) রিফ্রেশে re-fire করে না।
  // CONVERSATION RESUME (owner request 2026-10-24): history-rail links carry
  // ?conversation=<id> — the Studio reopens that conversation with its full
  // locally-persisted message history instead of only prefilling a prompt.
  useEffect(() => {
    const conv = searchParams.get('conversation');
    if (!conv || intentConsumedRef.current) return;
    intentConsumedRef.current = true;
    setSearchParams({}, { replace: true });
    setResumeConvId(conv);
  }, [searchParams, setSearchParams]);

  useEffect(() => {
    if (intentConsumedRef.current) return;
    const intent = searchParams.get('intent');
    if (!intent) return;
    intentConsumedRef.current = true;
    setSearchParams({}, { replace: true });
    setInput(intent);
    document.querySelector<HTMLInputElement>('[data-testid="chat-input"]')?.focus();
  }, [searchParams, setSearchParams]);

  return (
    <div className="relative flex h-full w-full flex-col overflow-hidden bg-[var(--sa-canvas)] text-[var(--sa-ink)]">
      <div className="pointer-events-none absolute inset-x-0 top-0 h-48 bg-[radial-gradient(circle_at_50%_0%,rgba(34,211,238,0.12),transparent_64%)]" aria-hidden="true" />
      {/* AI Studio contextual header */}
      <div className="relative flex min-h-16 shrink-0 flex-wrap items-center justify-between gap-2 border-b border-[var(--sa-border)] bg-[var(--sa-surface)]/80 px-4 backdrop-blur sm:px-6">
        <div className="flex items-center gap-4 text-xs font-medium">
          <button 
            type="button"
            onClick={() => setActiveTab('chat')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'chat' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Bot size={14} /> Conversation
          </button>
          <button 
            type="button"
            onClick={() => gotoSurface('preview')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'preview' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Code size={14} /> Browser Preview
          </button>
          <button 
            type="button"
            onClick={() => gotoSurface('mobile')}
            className={`flex items-center gap-2 rounded-[var(--sa-radius-sm)] border px-3 py-2 text-xs transition-colors ${activeTab === 'mobile' ? 'border-[var(--sa-primary)] bg-[var(--sa-primary-soft)] text-[var(--sa-primary)]' : 'border-transparent text-[var(--sa-ink-muted)] hover:border-[var(--sa-border)] hover:bg-[var(--sa-surface-raised)] hover:text-[var(--sa-ink)]'}`}
          >
            <Smartphone size={14} /> Mobile Simulator
          </button>
        </div>
        
        <div className="hidden items-center gap-4 text-[10px] uppercase tracking-widest text-[var(--sa-ink-muted)] sm:flex">
          <span className="flex items-center gap-1.5"><span className="size-1.5 rounded-full bg-emerald-400" />Agent: SupremeAI</span>
          <span className="flex items-center gap-1.5"><span className="size-1.5 rounded-full bg-[var(--sa-primary)]" />Model: Configured backend</span>
          <span className="rounded-full border border-[var(--sa-border)] px-2 py-1 text-[var(--sa-ink-muted)]">Context ready</span>
        </div>
      </div>

      <div className="flex-1 min-h-0 relative">
        {activeTab === 'chat' && (
          <div className="absolute inset-0 flex gap-4 p-4">
            {/* Unified Chat Phase 2: uses the canonical UnifiedChatPanel with live streaming,
                thinking indicator, brand badge, and intent carry-over */}
            <aside className="hidden w-56 shrink-0 flex-col gap-2 md:flex" data-testid="chat-history-rail">
              <button
                type="button"
                onClick={startNewChat}
                className="inline-flex items-center justify-center gap-2 rounded-xl border border-white/10 bg-slate-900/80 px-3 py-2.5 text-sm font-medium text-slate-200 transition hover:border-purple-400/40 hover:text-white"
              >
                <MessageSquarePlus size={15} /> New chat
              </button>
              <div className="flex min-h-0 flex-1 flex-col overflow-y-auto rounded-xl border border-white/10 bg-slate-900/40 p-2">
                <p className="px-2 pb-1 text-[10px] font-semibold uppercase tracking-wider text-slate-500">Recent</p>
                {history.length === 0 ? (
                  <p className="px-2 py-2 text-xs text-slate-500">Your conversations will appear here once you start chatting.</p>
                ) : (
                  <ul className="flex flex-col gap-1">
                    {history.map((h) => (
                      <li key={h.id}>
                        <button
                          type="button"
                          onClick={() => setResumeConvId(h.id)}
                          className={`w-full rounded-lg border px-2.5 py-2 text-left text-xs transition ${
                            h.id === resumeConvId
                              ? 'border-purple-500/40 bg-purple-500/10 text-slate-100'
                              : 'border-transparent text-slate-400 hover:border-white/10 hover:bg-white/[0.03] hover:text-slate-200'
                          }`}
                          title={h.title}
                        >
                          <span className="block truncate">{h.title}</span>
                          <span className="mt-0.5 block text-[10px] text-slate-600">
                            {new Date(h.updatedAt).toLocaleDateString()}
                          </span>
                        </button>
                      </li>
                    ))}
                  </ul>
                )}
              </div>
            </aside>
            <div className="relative min-w-0 flex-1">
            {/* RC-3 docked bar (report §6.4): contextual middle actions = the two
                REAL preview surfaces; Apps menu omitted (the tab strip above is
                this shell's IA — no duplicate). */}
            <UnifiedChatPanel
              key={resumeConvId ?? 'new'}
              fit="fill"
              initialConversationId={resumeConvId ?? undefined}
              showStarter={true}
              initialInput={input}
              onInputChange={setInput}
              showDock
              showSatisfactionPulse
              dockActions={[
                { id: 'preview', label: 'Preview', icon: Globe, onClick: () => gotoSurface('preview') },
                { id: 'mobile', label: 'Mobile', icon: Smartphone, onClick: () => gotoSurface('mobile') },
              ] satisfies DockAction[]}
              onPreview={(html) => {
                setCode(html);
                // MOBILE DUAL-PATH: agent-built preview opens on the surface the
                // user last chose (Browser বা Mobile) — force-jump নেই।
                setMobileSource('agent');
                gotoSurface(lastSurface);
              }}
            />
            </div>
          </div>
        )}

        {activeTab === 'preview' && (
          <div className="absolute inset-0 flex flex-col gap-3 p-4">
            <div className="flex h-full min-h-0 w-full flex-col gap-2">
              {!hasPreview && (
                <p className="shrink-0 rounded-lg border border-[var(--sa-border)] bg-[var(--sa-surface)]/60 px-3 py-2 text-[11px] leading-5 text-[var(--sa-ink-muted)]">
                  Nothing generated yet — ask the agent to build something, or type any
                  https:// URL below to browse it through the server-side browser.
                </p>
              )}
              <div className="min-h-0 flex-1">
                <LiveBrowserPreview
                  html={hasPreview ? code : undefined}
                  showDeviceToolbar
                  onNavigated={(u) => {
                    // MOBILE DUAL-PATH: Browser Preview-তে যা খোলা হলো (agent
                    // বা ইউজার — যেই navigation-ই হোক) সেটাই মোবাইল স্ক্রিনে mirror হবে।
                    setMirrorUrl(u);
                    setMobileSource('mirror');
                  }}
                />
              </div>
            </div>
          </div>
        )}

        {activeTab === 'mobile' && (
          <div className="absolute inset-0 flex flex-col gap-3 p-4">
            <MobileAutoPanel
              hasPreview={hasPreview}
              code={code}
              mirrorUrl={mirrorUrl}
              source={mobileSource}
              onSourceChange={setMobileSource}
              onBack={() => setActiveTab('chat')}
              onOpenUrl={(u) => {
                setMirrorUrl(u);
                setMobileSource('mirror');
              }}
              urlDraft={mobileUrlDraft}
              onUrlDraftChange={setMobileUrlDraft}
            />
          </div>
        )}
      </div>
    </div>
  );
};
